window.CFL_I18N = CFL_I18N;
window.CFL_getLang = () => localStorage.getItem("cfl-lang") || "en";
window.CFL_setLang = (lang) => {
  const next = lang === "es" ? "es" : "en";
  localStorage.setItem("cfl-lang", next);
  window.CFL_applyLang(next);
};

window.CFL_applyLang = (lang) => {
  const dict = CFL_I18N[lang] || CFL_I18N.en;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || dict[key] == null) return;
    el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (!key || dict[key] == null) return;
    el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key || dict[key] == null) return;
    el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (!key || dict[key] == null) return;
    el.setAttribute("aria-label", dict[key]);
  });

  const meta = document.querySelector('meta[name="description"]');
  const isTickets = document.body.classList.contains("page-tickets");
  if (meta) {
    meta.setAttribute("content", dict[isTickets ? "meta_description_tickets" : "meta_description"]);
  }
  document.title = dict[isTickets ? "title_tickets" : "title_home"];

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    btn.classList.toggle("is-active", btn.getAttribute("data-lang") === lang);
    btn.setAttribute("aria-pressed", String(btn.getAttribute("data-lang") === lang));
  });

  window.dispatchEvent(new CustomEvent("cfl:langchange", { detail: { lang, dict } }));
};
